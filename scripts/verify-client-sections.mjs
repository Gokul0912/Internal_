import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { chromium } from "playwright";

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await context.addInitScript(() => {
  if (localStorage.getItem("sections-seeded")) return;
  localStorage.setItem("sections-seeded", "yes");
  localStorage.setItem("product-log.clients.v1", JSON.stringify({ products: ["Moments", "Other product"], clients: [{ id: "11111111-1111-4111-8111-111111111111", company: "Legacy client", website: "", address: "", notes: "", archived: false, products: ["Moments"], contacts: [] }] }));
});
const page = await context.newPage();
page.setDefaultTimeout(12000);
const errors = [];
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
const modal = name => page.getByRole("dialog", { name, exact: true });
async function createSection(product, name) {
  const manager = modal("Manage client sections");
  await manager.getByRole("combobox", { name: "Product", exact: true }).selectOption(product);
  await manager.getByRole("textbox", { name: "New section", exact: true }).fill(name);
  await manager.getByRole("button", { name: "Create section", exact: true }).click();
  await manager.locator('[class*="catalogRow"]').filter({ hasText: new RegExp("^" + name) }).waitFor();
}
await mkdir(".next/qa", { recursive: true });
try {
  await page.goto("http://127.0.0.1:3000/");
  await page.getByRole("button", { name: "Clients", exact: true }).click();
  await page.getByRole("button", { name: "Manage sections", exact: true }).click();
  await createSection("Moments", "Food");
  await createSection("Moments", "Drinks");
  await createSection("Other product", "Food");
  await modal("Manage client sections").getByRole("button", { name: "Close sections", exact: true }).click();
  await page.getByRole("button", { name: "Add client", exact: true }).click();
  const editor = modal("Add client");
  await editor.getByRole("textbox", { name: "Company name", exact: true }).fill("Section client");
  await editor.getByRole("checkbox", { name: "Moments", exact: true }).check();
  await editor.getByRole("checkbox", { name: "Food", exact: true }).check();
  await editor.getByRole("checkbox", { name: "Drinks", exact: true }).check();
  await editor.getByRole("button", { name: "Manage sections", exact: true }).click();
  await createSection("Moments", "Watches");
  await modal("Manage client sections").getByRole("button", { name: "Close sections", exact: true }).click();
  await modal("Manage client sections").waitFor({ state: "hidden" });
  assert.equal(await editor.getByRole("textbox", { name: "Company name", exact: true }).inputValue(), "Section client");
  await editor.getByRole("checkbox", { name: "Watches", exact: true }).check();
  await editor.getByRole("button", { name: "Save client", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  const product = page.getByRole("combobox", { name: "Product", exact: true });
  const section = page.getByRole("combobox", { name: "Section", exact: true });
  await product.selectOption("Moments");
  const food = await section.locator("option").filter({ hasText: /^Food$/ }).getAttribute("value");
  await section.selectOption(food);
  await page.getByRole("button", { name: /Section client/ }).waitFor();
  assert.equal(await page.getByRole("button", { name: /Legacy client/ }).count(), 0);
  await section.selectOption("unassigned");
  await page.getByRole("button", { name: /Legacy client/ }).waitFor();
  assert.equal(await page.getByRole("button", { name: /Section client/ }).count(), 0);
  await product.selectOption("Other product");
  assert.equal(await section.inputValue(), "");
  const otherFood = await section.locator("option").filter({ hasText: /^Food$/ }).getAttribute("value");
  assert.notEqual(food, otherFood);
  await section.selectOption(otherFood);
  await page.getByRole("heading", { name: "No matching clients", exact: true }).waitFor();
  await product.selectOption("Moments");
  await page.getByRole("button", { name: /Section client/ }).click();
  await modal("Client details").getByRole("button", { name: "Edit client", exact: true }).click();
  const edit = modal("Edit client");
  await edit.getByRole("checkbox", { name: "Moments", exact: true }).uncheck();
  await edit.getByRole("checkbox", { name: "Other product", exact: true }).check();
  assert.equal(await edit.getByRole("checkbox", { name: "Food", exact: true }).isChecked(), false);
  await edit.getByRole("checkbox", { name: "Food", exact: true }).check();
  await edit.getByRole("button", { name: "Save client", exact: true }).click();
  await edit.waitFor({ state: "hidden" });
  await product.selectOption("Other product");
  await section.selectOption(otherFood);
  await page.getByRole("button", { name: /Section client/ }).click();
  await modal("Client details").getByText("Other product: Food", { exact: true }).waitFor();
  await modal("Client details").getByRole("button", { name: "Close client", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: "Clients", exact: true }).click();
  await product.selectOption("Other product");
  await section.selectOption(otherFood);
  await page.getByRole("button", { name: /Section client/ }).waitFor();
  await page.screenshot({ path: ".next/qa/client-sections-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: ".next/qa/client-sections-mobile.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: legacy clients, product-scoped creation, same name in different products, nested manager preserves form, multi-section selection, dependent filters, edit clears stale assignments, refresh, mobile layout.");
} catch (error) {
  await page.screenshot({ path: ".next/qa/client-sections-failure.png", fullPage: true });
  console.error(await page.locator("body").innerText());
  throw error;
} finally { await context.close(); await browser.close(); }
